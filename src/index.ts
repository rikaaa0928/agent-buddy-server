// 1. GET /v0/management/auth-files (Called by agent-buddy)
app.get("/v0/management/auth-files", async (c) => {
  const nameFilter = c.req.query("name")?.trim();
  const authIndexFilter = c.req.query("auth_index")?.trim();

  let creds = await listCredentials(c.env);

  if (nameFilter) {
    creds = creds.filter(
      (item) => item.name === nameFilter || item.id === nameFilter || item.name.replace(/\.json$/, "") === nameFilter
    );
  }
  if (authIndexFilter) {
    creds = creds.filter((item) => item.auth_index === authIndexFilter);
  }

  const files = creds.map((r) => ({
    id: r.id,
    auth_index: r.auth_index,
    name: r.name,
    provider: r.provider,
    type: r.type,
    status: r.status,
    disabled: r.disabled,
    project_id: r.project_id || null,
    email: r.email || null,
    account_type: r.plan_type || null,
    created_at: new Date(r.created_at).toISOString(),
    updated_at: new Date(r.updated_at).toISOString(),
  }));

  return c.json({ files });
});

