// 7. Kimi Device Flow Polling
app.get("/v0/management/kimi-poll", async (c) => {
  const state = c.req.query("state");
  if (!state) {
    return c.json({ error: "missing state" }, 400);
  }

  const session = await getOAuthSession(c.env, state);
  if (!session || !session.device_code) {
    return c.json({ error: "session expired or invalid" }, 404);
  }

  const pollRes = await pollKimiToken(session.device_code);
  if (pollRes.status === "pending") {
    return c.json({ status: "pending" });
  }

  if (pollRes.status === "error") {
    return c.json({ status: "error", message: pollRes.message });
  }

  const existing = await listCredentials(c.env);
  const authIdx = `kimi-${existing.length}`;
  const credId = `kimi-${Date.now()}`;
  const credName = `kimi-${pollRes.email || "user"}.json`;

  const cred: CredentialRecord = {
    id: credId,
    auth_index: authIdx,
    name: credName,
    provider: "kimi",
    type: "kimi",
    status: "active",
    disabled: false,
    email: pollRes.email,
    plan_type: pollRes.plan_type,
    access_token: pollRes.access_token,
    refresh_token: pollRes.refresh_token,
    expires_at: Date.now() + pollRes.expires_in * 1000,
    created_at: Date.now(),
    updated_at: Date.now(),
  };

  await saveCredential(c.env, cred);
  await deleteOAuthSession(c.env, state);

  return c.json({ status: "success", completed: true, credential: cred });
});

// 8. OAuth Callback (Codex, Claude, Antigravity)
app.post("/v0/management/oauth-callback", async (c) => {
  let body: {
    provider?: string;
    redirect_url?: string;
    code?: string;
    state?: string;
    error?: string;
  };

  try {
    body = await c.req.json();
  } catch {
    return c.json({ status: "error", error: "invalid JSON body" }, 400);
  }

  let state = (body.state || "").trim();
  let code = (body.code || "").trim();
  let error = (body.error || "").trim();

  // Extract from redirect_url if provided
  if (body.redirect_url) {
    try {
      const parsedUrl = new URL(body.redirect_url);
      if (!code && parsedUrl.searchParams.has("code")) {
        code = parsedUrl.searchParams.get("code") || "";
      }
      if (!state && parsedUrl.searchParams.has("state")) {
        state = parsedUrl.searchParams.get("state") || "";
      }
      if (!error && parsedUrl.searchParams.has("error")) {
        error = parsedUrl.searchParams.get("error") || "";
      }
    } catch {
      // String parsing fallback
      const mCode = body.redirect_url.match(/[?&#]code=([^&#\s]+)/);
      if (mCode && !code) code = decodeURIComponent(mCode[1]);
      const mState = body.redirect_url.match(/[?&#]state=([^&#\s]+)/);
      if (mState && !state) state = decodeURIComponent(mState[1]);
      const mErr = body.redirect_url.match(/[?&#]error=([^&#\s]+)/);
      if (mErr && !error) error = decodeURIComponent(mErr[1]);
    }
  }

  if (error) {
    return c.json({ status: "error", error: `OAuth provider error: ${error}` }, 400);
  }

  if (!state) {
    return c.json({ status: "error", error: "state parameter is required" }, 400);
  }

  const session = await getOAuthSession(c.env, state);
  if (!session) {
    return c.json({ status: "error", error: "OAuth session not found or expired" }, 404);
  }

  const provider = (session.provider || body.provider || "").toLowerCase() as ProviderType;
  if (!code) {
    return c.json({ status: "error", error: "authorization code is required" }, 400);
  }

  try {
    const existing = await listCredentials(c.env);
    let tokenData: any;

    if (provider === "codex") {
      tokenData = await exchangeCodexCode(code, session.pkce_verifier || "");
    } else if (provider === "claude") {
      tokenData = await exchangeClaudeCode(code, session.pkce_verifier || "", state);
    } else if (provider === "antigravity") {
      tokenData = await exchangeAntigravityCode(code);
    } else {
      return c.json({ status: "error", error: `unsupported provider: ${provider}` }, 400);
    }

    const authIdx = `${provider}-${existing.length}`;
    const credId = `${provider}-${Date.now()}`;
    const emailSanitized = (tokenData.email || "user").replace(/[^a-zA-Z0-9@._-]/g, "");
    const credName = `${provider}-${emailSanitized}.json`;

    const cred: CredentialRecord = {
      id: credId,
      auth_index: authIdx,
      name: credName,
      provider: provider,
      type: provider,
      status: "active",
      disabled: false,
      email: tokenData.email,
      project_id: tokenData.project_id || undefined,
      plan_type: tokenData.plan_type,
      access_token: tokenData.access_token,
      refresh_token: tokenData.refresh_token,
      expires_at: Date.now() + (tokenData.expires_in || 3600) * 1000,
      created_at: Date.now(),
      updated_at: Date.now(),
    };

    await saveCredential(c.env, cred);
    await deleteOAuthSession(c.env, state);

    return c.json({
      status: "ok",
      credential: {
        id: cred.id,
        auth_index: cred.auth_index,
        name: cred.name,
        provider: cred.provider,
        email: cred.email,
        project_id: cred.project_id,
        plan_type: cred.plan_type,
      },
    });
  } catch (err: any) {
    console.error("Token exchange failed:", err);
    return c.json({ status: "error", error: err.message }, 500);
  }
});

