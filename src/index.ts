// 11. PATCH /v0/management/auth-files/status (Toggle disabled)
app.patch("/v0/management/auth-files/status", async (c) => {
  const body = await c.req.json<{ name: string; disabled?: boolean }>();
  if (!body.name) return c.json({ error: "missing name" }, 400);

  const cred = await getCredentialByAuthIndex(c.env, body.name);
  if (!cred) return c.json({ error: "credential not found" }, 404);

  if (body.disabled !== undefined) {
    cred.disabled = body.disabled;
    cred.status = cred.disabled ? "disabled" : "active";
    await saveCredential(c.env, cred);
  }

  return c.json({ status: "ok" });
});

// 12. POST /v0/management/auth-files (Direct JSON Import / Upload)
app.post("/v0/management/auth-files", async (c) => {
  let raw: any;
  try {
    raw = await c.req.json();
  } catch {
    return c.json({ error: "invalid JSON body" }, 400);
  }

  const existing = await listCredentials(c.env);
  let provider: ProviderType = "codex";
  const typeStr = (raw.type || raw.provider || "").toLowerCase();

  if (typeStr.includes("claude") || typeStr.includes("anthropic")) {
    provider = "claude";
  } else if (typeStr.includes("antigravity") || typeStr.includes("cloudcode") || typeStr.includes("google")) {
    provider = "antigravity";
  } else if (typeStr.includes("kimi") || typeStr.includes("moonshot")) {
    provider = "kimi";
  } else if (typeStr.includes("codex") || typeStr.includes("openai")) {
    provider = "codex";
  }

  let accessToken = raw.access_token || raw.token || "";
  let refreshToken = raw.refresh_token || "";
  let projectId = raw.project_id || "";
  let email = raw.email || "";
  let planType = raw.plan_type || "";

  // Nested structures (e.g. token_data in Codex/Claude CLIProxyAPI bundles)
  if (raw.token_data && typeof raw.token_data === "object") {
    accessToken = raw.token_data.access_token || accessToken;
    refreshToken = raw.token_data.refresh_token || refreshToken;
    email = raw.token_data.email || email;
  }

  if (!accessToken && !refreshToken) {
    return c.json({ error: "JSON must contain access_token or refresh_token" }, 400);
  }

  const authIdx = `${provider}-${existing.length}`;
  const credId = `${provider}-${Date.now()}`;
  const credName = raw.name || `${provider}-${email ? email.replace(/[^a-zA-Z0-9@._-]/g, "") : Date.now()}.json`;

  const cred: CredentialRecord = {
    id: credId,
    auth_index: authIdx,
    name: credName,
    provider: provider,
    type: provider,
    status: "active",
    disabled: false,
    email: email || undefined,
    project_id: projectId || undefined,
    plan_type: planType || undefined,
    access_token: accessToken,
    refresh_token: refreshToken || undefined,
    expires_at: raw.expires_at || Date.now() + 3600 * 1000,
    created_at: Date.now(),
    updated_at: Date.now(),
  };

  await saveCredential(c.env, cred);
  return c.json({ status: "ok", name: cred.name, auth_index: cred.auth_index });
});

