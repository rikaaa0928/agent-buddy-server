// Management Auth Middleware for /v0/management/*
app.use("/v0/management/*", async (c, next) => {
  const { key: configuredKey } = await getOrInitManagementKey(c.env);

  // Extract auth key from headers, query, or cookie
  const authHeader = c.req.header("Authorization") || "";
  const xKey = c.req.header("X-Management-Key") || "";
  const queryKey = c.req.query("key") || c.req.query("management_key") || "";

  let providedKey = "";
  if (authHeader.startsWith("Bearer ")) {
    providedKey = authHeader.slice(7).trim();
  } else if (authHeader) {
    providedKey = authHeader.trim();
  } else if (xKey) {
    providedKey = xKey.trim();
  } else if (queryKey) {
    providedKey = queryKey.trim();
  }

  if (providedKey !== configuredKey) {
    return c.json({ error: "unauthorized: invalid management key" }, 401);
  }

  return await next();
});

